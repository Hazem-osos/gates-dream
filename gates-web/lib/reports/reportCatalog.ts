function inventoryPreviewFix(
  slug: string,
  titleAr: string
): Record<string, ReportCatalogEntry> {
  const filterPath = `/inventory/reports/${slug}`;
  const previewPath = `${filterPath}/preview`;
  const base = {
    registryPath: `inventory/reports/${slug}`,
    reportKey: slug,
    titleAr,
    module: 'inventory',
    status: 'active' as const,
    previewPath,
    filterPath,
  };
  return {
    [filterPath]: { ...base, urlPath: filterPath, kind: 'filter' },
    [previewPath]: { ...base, urlPath: previewPath, kind: 'preview' },
  };
}

