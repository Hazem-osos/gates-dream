/** Trial-balance account class: أصول، التزامات، حقوق الملكية، إيرادات، مصروفات. */
export function accountTypeLabel(value: unknown): string {
  const raw = typeof value === 'string' ? value.trim() : '';
  if (!raw) return '';
  const key = raw.toLowerCase();
  if (ACCOUNT_TYPE_AR[key]) return ACCOUNT_TYPE_AR[key];
  if (raw.includes('إيراد')) return 'إيرادات';
  if (raw.includes('مصروف') || raw.includes('تكلفة المبيعات')) return raw.includes('تكلفة') ? 'تكلفة المبيعات' : 'مصروفات';
  if (raw.includes('أصل')) return 'أصول';
  if (raw.includes('التزام') || raw.includes('خصوم')) return 'التزامات';
  if (raw.includes('ملك')) return 'حقوق الملكية';
  return raw;
}
