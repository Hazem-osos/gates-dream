export function preserveConfigForTable(table: string): ImporterPreserveConfig | undefined {
  return IMPORTER_PRESERVE_CONFIG[table];
}

export function isConfiguredMappedColumn(table: string, column: string): boolean {
  const cfg = preserveConfigForTable(table);
  if (!cfg) return false;
  return cfg.mappedColumns.has(column);
}
