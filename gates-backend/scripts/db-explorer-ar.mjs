function splitName(name) {
  return name
    .replace(/Id$/, '')
    .replace(/([a-z])([A-Z])/g, '$1 $2')
    .replace(/_/g, ' ')
    .split(' ')
    .filter(Boolean)
    .map((w) => w.toLowerCase());
}

export function labelColumn(name) {
  if (COLUMN_GLOSSARY[name]) return COLUMN_GLOSSARY[name][0];
  const parts = splitName(name).map((w) => WORDS[w] || w);
  return parts.join(' ');
}

export function explainColumn(name, comment) {
  if (COLUMN_GLOSSARY[name]) {
    const extra = comment ? ` ${comment}` : '';
    return COLUMN_GLOSSARY[name][1] + extra;
  }
  if (comment) return comment;
  if (name.endsWith('Id') && name !== 'id') {
    return `مفتاح أجنبي يربط الصف بجدول «${labelColumn(name)}».`;
  }
  if (name.endsWith('At')) return 'ختم زمني لهذا الحدث.';
  if (name.startsWith('is') || name.startsWith('can') || name.startsWith('has') || name.startsWith('show')) {
    return `علامة نعم/لا: ${labelColumn(name)}.`;
  }
  return `حقل «${labelColumn(name)}» على هذا الجدول.`;
}

export function explainRelation(rel, targetTitle) {
  const target = targetTitle || rel.targetModel;
  if (rel.cardinality === '1-N') {
    return `هذا الجدول أب: صف واحد هنا له أكثر من «${target}».`;
  }
  if (rel.cardinality === 'N-0..1') {
    return `ربط اختياري بصف واحد من «${target}»` + (rel.fkFields.length ? ` عبر ${rel.fkFields.join(', ')}` : '') + '.';
  }
  return `كل صف هنا مربوط بصف واحد من «${target}»` + (rel.fkFields.length ? ` عبر ${rel.fkFields.join(', ')}` : '') + '.';
}

