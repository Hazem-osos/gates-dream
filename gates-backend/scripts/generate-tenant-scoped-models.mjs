#!/usr/bin/env node
/**
 * Regenerates src/shared/database/tenant-scoped-models.generated.ts from
 * prisma/schema.prisma: every model with a direct `companyId String` field
 * is tenant-scoped and gets auto-filtered by the Prisma tenant-scoping
 * extension (Item 37). Re-run this after adding/removing a model's
 * `companyId` field.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SCHEMA = path.join(__dirname, '../prisma/schema.prisma');
const OUT = path.join(__dirname, '../src/shared/database/tenant-scoped-models.generated.ts');

const src = fs.readFileSync(SCHEMA, 'utf-8');
const modelRe = /model\s+(\w+)\s*\{([^}]*)\}/gs;
const scoped = [];
let m;
while ((m = modelRe.exec(src))) {
  const [, name, body] = m;
  if (/^\s*companyId\s+String/m.test(body)) {
    scoped.push(name);
  }
}
scoped.sort();

const toDelegate = (n) => n.charAt(0).toLowerCase() + n.slice(1);
const delegates = scoped.map(toDelegate);

const out = `/**
 * AUTO-GENERATED by scripts/generate-tenant-scoped-models.mjs — do not edit.
 * Regenerate: node scripts/generate-tenant-scoped-models.mjs
 *
 * Prisma delegate names (lowerCamelCase model names) for every model with a
 * direct \`companyId String\` field in prisma/schema.prisma. Used by the
 * tenant-scoping Prisma extension (Item 37) to know which models to
 * auto-filter/auto-stamp by companyId.
 */
export const TENANT_SCOPED_MODELS = new Set<string>([
${delegates.map((d) => `  '${d}',`).join('\n')}
]);
`;

fs.writeFileSync(OUT, out);
console.log(`Wrote ${delegates.length} tenant-scoped model delegate names to ${path.relative(process.cwd(), OUT)}`);
