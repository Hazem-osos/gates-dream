#!/usr/bin/env node
/**
 * Generates gates-backend/src/modules/platform/data/legacy-settings-defaults.ts
 * from docs/parity/legacy-settings-catalog.json (built by
 * extract-settings-catalog.mjs from untcompanyvariables.pas).
 *
 * Each company-scope legacy setting key gets its exact legacy default value,
 * decoded from the Pascal literal captured at parse time, so the web
 * settings engine returns legacy-exact values for absent CompanySetting rows
 * instead of an ad-hoc guess.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '../../..');
const CATALOG_PATH = path.join(ROOT, 'docs/parity/legacy-settings-catalog.json');
const OUT_PATH = path.join(
  ROOT,
  'gates-backend/src/modules/platform/data/legacy-settings-defaults.ts'
);

/**
 * A handful of keys whose true default the mechanical .pas scan could not
 * capture as a literal (defaultExpr came back null/dynamic). Verified by
 * direct inspection of untcompanyvariables.pas at parse time:
 * - WorkType: `if not found then WorkType := 'AVG'` (untcompanyvariables.pas:788)
 * - CurrencyCode: default is the company's own base currency, not a literal —
 *   handled dynamically in company-setting.service.ts (COMPANY_CURRENCY_KEY),
 *   not via this static table.
 */
const OVERRIDES = {
  WorkType: { valueKind: 'string', defaultValue: 'AVG' },
};

const DYNAMIC_KEYS = new Set(['CurrencyCode']);

function decodePascalLiteral(expr) {
  if (expr == null) return null;
  const trimmed = expr.trim();
  const stringMatch = trimmed.match(/^'((?:[^']|'')*)'$/);
  if (stringMatch) {
    return stringMatch[1].replace(/''/g, "'");
  }
  if (/^-?\d+$/.test(trimmed)) {
    return trimmed;
  }
  return undefined; // unrecognized expression form
}

function main() {
  const catalog = JSON.parse(readFileSync(CATALOG_PATH, 'utf8'));
  const entries = [];
  const skipped = [];

  for (const item of catalog.catalog) {
    const { key } = item;
    if (DYNAMIC_KEYS.has(key)) continue;

    if (OVERRIDES[key]) {
      entries.push({ key, ...OVERRIDES[key] });
      continue;
    }

    const decoded = decodePascalLiteral(item.defaultExpr);
    if (decoded === undefined) {
      skipped.push({ key, defaultExpr: item.defaultExpr });
      continue;
    }
    const valueKind = decoded === 'T' || decoded === 'F' ? 'flag' : 'string';
    entries.push({ key, valueKind, defaultValue: decoded });
  }

  entries.sort((a, b) => a.key.localeCompare(b.key));

  const lines = [];
  lines.push('// AUTO-GENERATED by gates-backend/scripts/legacy/generate-settings-defaults.mjs');
  lines.push('// Source: docs/parity/legacy-settings-catalog.json (untcompanyvariables.pas set_variables defaults).');
  lines.push('// Do not hand-edit — re-run the generator after re-scanning the legacy catalog.');
  lines.push('');
  lines.push("export type LegacySettingValueKind = 'flag' | 'string';");
  lines.push('');
  lines.push('export interface LegacySettingDefault {');
  lines.push('  key: string;');
  lines.push('  valueKind: LegacySettingValueKind;');
  lines.push('  /** Raw legacy default, stored the same way CompanySettingEntry.value would be (T/F flags as literal strings). */');
  lines.push('  defaultValue: string;');
  lines.push('}');
  lines.push('');
  lines.push('export const LEGACY_SETTINGS_DEFAULTS: Record<string, LegacySettingDefault> = {');
  for (const e of entries) {
    lines.push(
      `  ${JSON.stringify(e.key)}: { key: ${JSON.stringify(e.key)}, valueKind: ${JSON.stringify(
        e.valueKind
      )}, defaultValue: ${JSON.stringify(e.defaultValue)} },`
    );
  }
  lines.push('};');
  lines.push('');
  lines.push(
    '/** Keys whose legacy default is dynamic (not a static literal) and must be resolved at runtime. */'
  );
  lines.push(
    `export const DYNAMIC_DEFAULT_KEYS = ${JSON.stringify([...DYNAMIC_KEYS])} as const;`
  );
  lines.push('');

  writeFileSync(OUT_PATH, lines.join('\n'), 'utf8');

  console.log(`Wrote ${entries.length} legacy setting defaults to ${OUT_PATH}`);
  if (skipped.length) {
    console.log('Skipped (unrecognized defaultExpr form):', skipped);
  }
}

main();
